function tool(name, status = "success") {
  return { name, status };
}

function numericRequired(extra = {}) {
  return {
    mode: "required",
    minCitationCount: 1,
    uncitedNumbersAllowed: 0,
    maxToolCallsPerTurn: 3,
    ...extra,
  };
}

function numericConditional(extra = {}) {
  return {
    mode: "conditional",
    minCitationCount: 1,
    uncitedNumbersAllowed: 0,
    maxToolCallsPerTurn: 3,
    ...extra,
  };
}

function numericForbidden(extra = {}) {
  return {
    mode: "forbidden",
    minCitationCount: 0,
    uncitedNumbersAllowed: 0,
    maxToolCallsPerTurn: 3,
    ...extra,
  };
}

function scenario({
  id,
  level,
  prompt,
  bsIsCfRequired,
  edgeTags,
  requiredTools,
  endpointIncludes,
  allowedPolicyStatuses,
  numericRule,
  oracle,
  contextSnapshot,
}) {
  return {
    id,
    level,
    prompt,
    hoseOnly: true,
    bsIsCfRequired: Boolean(bsIsCfRequired),
    edgeTags,
    contextSnapshot: contextSnapshot ?? { page: "home" },
    expected: {
      requiredTools,
      endpointIncludes,
      allowedPolicyStatuses,
      numericRule,
      oracle,
    },
  };
}

